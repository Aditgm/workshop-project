function isActivePath(pathname: string, href: string) {
  return href === "/admin" ? pathname === href : pathname.startsWith(href);
}

export function AdminNav({ variant = "desktop" }: { variant?: "desktop" | "mobile" }) {
  const pathname = usePathname();
  const desktop = variant === "desktop";

  return (
    <nav
      aria-label="Admin sections"
      className={desktop ? "space-y-1" : "flex flex-wrap gap-1"}
    >
      {items.map((item) => {
        const active = isActivePath(pathname, item.href);

        return (
          <Link
            key={item.href}
            href={item.href}
            aria-current={active ? "page" : undefined}
            className={
              desktop
                ? `group flex items-center gap-3 rounded-[2px] px-3 py-2.5 text-sm font-medium transition-colors ${
                    active
                      ? "bg-gold/10 text-gold-soft ring-1 ring-inset ring-gold/20"
                      : "text-cream/40 hover:bg-cream/[0.045] hover:text-cream/80"
                  }`
                : `inline-flex items-center gap-2 rounded-[2px] px-3 py-2 text-xs font-medium transition-colors ${
                    active
                      ? "bg-gold text-navy-deep"
                      : "text-cream/45 hover:bg-cream/[0.055] hover:text-cream"
                  }`
            }
          >
            <svg
              viewBox="0 0 24 24"
              fill="none"
              stroke="currentColor"
              strokeWidth="1.6"
              className={desktop ? "size-5 shrink-0" : "size-4 shrink-0"}
              aria-hidden="true"
            >
              {item.icon}
            </svg>
            {item.label}
          </Link>
        );
      })}
    </nav>
  );
}
